package Tugas;

public class Mahasiswa {
    public String nim;
    public String nama;
    public String jurusan;
    public char nilaiHuruf;

    public Mahasiswa(String nim, String nama, String jurusan, char nilaiHuruf) {
        this.nim = nim;
        this.nama = nama;
        this.jurusan = jurusan;
        this.nilaiHuruf = nilaiHuruf;
    }
}